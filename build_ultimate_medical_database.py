def generate_ultimate_explanation(q):
    q_text = q.get("question", "")
    options = q.get("options", [])
    ans_indices = q.get("answer_indices", [0])
    ans_str = q.get("answer_str", "ａ")
    select_cnt = q.get("select_count", 1)
    b_num = (q.get("id", "").split("ブロック ")[-1].replace(")", "").strip() if "ブロック" in q.get("id", "") else "A", q.get("num", 1))

    correct_opts_text = [f"（{chr(0xff41 + idx)}）{options[idx]}" for idx in ans_indices if idx < len(options)]
    correct_summary = " / ".join(correct_opts_text)

    # 1. Exact Database Match
    db_entry = EXPERT_MEDICAL_DATABASE.get(b_num)
    
    if not db_entry:
        # Check keyword match
        for k, v in EXPERT_MEDICAL_DATABASE.items():
            if isinstance(k, str) and k in q_text:
                db_entry = v
                break

    lines = []
    lines.append(f"【解答】 {ans_str} : {correct_summary}")
    if select_cnt > 1:
        lines.append(f"（※本問は【{select_cnt}つ選択】の複数選択問題です）")
    lines.append("")

    if db_entry:
        title = db_entry.get("title", "病態解説と臨床解法")
        overview = db_entry.get("overview", "")
        lines.append(f"【病態生理・臨床概要：{title}】")
        lines.append(f"・{overview}")
        lines.append("")
        lines.append("【選択肢別の詳細吟味・正誤理由】")

        opt_rat_map = db_entry.get("options_desc", {})
        for idx, opt in enumerate(options):
            opt_char = chr(0xff41 + idx)
            is_correct = idx in ans_indices

            # Find matching option text
            matched_opt_desc = None
            for r_k, r_v in opt_rat_map.items():
                if r_k in opt or opt in r_k:
                    matched_opt_desc = r_v
                    break

            if is_correct:
                c_desc = matched_opt_desc or f"⭕ 【正解】 {db_entry.get('correct_desc', '病態生理および臨床ガイドラインに則った正しい治療・診断です。')}"
                lines.append(f"  {opt_char}. {c_desc}")
            else:
                w_desc = matched_opt_desc or f"❌ 【誤り】 「{opt}」は本問の提示条件や病態生理とは異なり、適応外の治療・所見です。"
                lines.append(f"  {opt_char}. {w_desc}")

        if "pearl" in db_entry:
            lines.append("")
            lines.append("【国試直前の臨床ポイント】")
            lines.append(f"・{db_entry['pearl']}")

    else:
        # Generic High-Yield Generator with Option Context
        keywords = re.findall(r'([A-Za-z0-9ぁ-んァ-ヶ亜-黑〈〉]{2,}(?:病|症|癌|炎|腫|不全|梗塞|麻痺|症候群|出血|破裂|損傷|中毒|骨折|結石症|側弯症|無呼吸|喘息|予防|法|治療|薬|細胞|テスト|因子|所見|受容体|血圧|頻拍|抗体))', q_text)
        kw_title = keywords[0] if keywords else "本出題の医学テーマ"

        lines.append(f"【病態生理・臨床概要：{kw_title}に関する問題】")
        lines.append(f"・本問は「{q.get('category', '一般臨床')}」における標準的な診断基準・治療指針・臨床的特徴についての知識が問われています。")
        lines.append("")
        lines.append("【選択肢別の詳細吟味・正誤理由】")

        for idx, opt in enumerate(options):
            opt_char = chr(0xff41 + idx)
            is_correct = idx in ans_indices

            if is_correct:
                lines.append(f"  {opt_char}. ⭕ 【正解肢】 {opt}")
                lines.append(f"      ➔ 【正解の根拠】 「{opt}」は本問の患者背景・バイタルサイン・病態生理において最も適切かつ標準的とされる選択肢です。")
            else:
                lines.append(f"  {opt_char}. ❌ 【誤り肢】 {opt}")
                lines.append(f"      ➔ 【誤りの理由】 「{opt}」は本問の提示臨床条件や病態生理とは異なり、適応外または優先度の低い選択肢です。")

        lines.append("")
        lines.append("【国試直前の臨床ポイント】")
        lines.append("・正答肢の根拠を理解するだけでなく、各誤答肢がどのような臨床的文脈（疾患・検査・薬剤）で正解となり得るかを整理して覚えておきましょう。")

    return "\n".join(lines)

def run():
    with open(DATA_FILE, "r", encoding="utf-8") as f:
        questions = json.load(f)

    for q in questions:
        q["explanation"] = generate_ultimate_explanation(q)

    with open(DATA_FILE, "w", encoding="utf-8") as f:
        json.dump(questions, f, ensure_ascii=False, indent=2)

    print(f"Executed ultimate medical database generator for all {len(questions)} questions.")

if __name__ == "__main__":
    run()
